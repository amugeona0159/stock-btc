# --- 지수 -------------------------------------------------------------------
# 매수 후보에서는 빠지지만(`universe.NOT_BUYABLE`) 학습 동료로 남아 있어서
# 진단 화면에는 나올 수 있다.
INDICES: dict[str, str] = {
    "^GSPC": "S&P 500",
    "^IXIC": "나스닥 종합",
}

_STOCKS: dict[str, str] = {**KR_STOCKS, **US_STOCKS, **INDICES}


def of(symbol: str) -> str | None:
    """이 종목의 한글 이름. 표에 없으면 `None` — **지어내지 않는다.**

    코인은 거래쌍을 떼고 찾으므로 `SOLUSDT` 와 `KRW-SOL` 이 같은 이름을 받는다.
    """
    if symbol in _STOCKS:
        return _STOCKS[symbol]
    return COINS.get(coins.base(symbol))


def ticker(symbol: str) -> str:
    """화면에 이름과 나란히 붙일 짧은 기호.

    코인은 거래쌍을 뗀 것(`SOLUSDT` → `SOL`), 주식은 심볼 그대로다. 국내주식의
    6자리 코드도 그대로 둔다 — 그게 사람들이 검색에 넣는 값이다.
    """
    return symbol if symbol in _STOCKS else coins.base(symbol)
