"""화면에 쓸 종목 이름 — **한 벌만.**

`AAPL`·`005930`·`SOLUSDT` 는 전부 사람이 읽는 이름이 아니다. 추천 목록은 이 도구에서
제일 자주 읽는 화면이라, 거기서 티커를 외우고 있어야 읽히면 안 된다.

## 이름은 토스에서 받아 적었다

지어내지 않았다. `/api/symbols?provider=toss_kr|toss_us` 가 돌려주는 이름을 그대로
옮겼다(2026-08). 토스는 국내주식 4,303종·미국주식 10,540종의 한글 이름을 들고 있다 —
"제이피모건 체이스"·"알파벳 A" 처럼 조금 어색해 보이는 것도 **거래 화면에서 쓰는 그
이름**이라 그대로 둔다. 내가 다듬으면 사용자가 토스에서 본 이름과 달라진다.

## 왜 실행 중에 조회하지 않나

세 가지다.

- **Actions 는 토스에 못 닿는다**(IP 허용 목록). 거기서 뽑는 미국주식 추천에 이름이
  안 붙는다.
- 추천을 읽는 API 는 **읽기 전용**이다. 화면을 열 때마다 바깥에 나가면 안 된다.
- 조회가 실패한 날 이름이 통째로 사라진다. 유니버스는 스무 종목 남짓이라 표로 두는
  값이 훨씬 싸다.

**유니버스를 늘리면 여기도 같이 늘린다.** 없으면 티커가 그대로 나가고, 그건 고장이
아니라 그냥 이름이 없는 것이다 — 없는 이름을 지어내면 다른 종목과 헷갈린다.
"""
